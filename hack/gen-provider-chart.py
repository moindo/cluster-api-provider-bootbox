#!/usr/bin/env python3
"""Render CRDs and RBAC from config/ into the provider chart.

Names keep the capi-bootbox- prefix of the kustomize install, so an existing
install can be adopted by the chart. Usage: gen-provider-chart.py <chart dir>
"""
import pathlib, subprocess, sys, tempfile

chart = pathlib.Path(sys.argv[1]).resolve()
root = pathlib.Path(__file__).resolve().parent.parent
with tempfile.TemporaryDirectory(dir=root) as tmp:
    (pathlib.Path(tmp) / "kustomization.yaml").write_text(f"""namespace: NAMESPACE_PLACEHOLDER
namePrefix: capi-bootbox-
resources:
  - ../config/crd
  - ../config/rbac
labels:
  - pairs:
      app.kubernetes.io/name: cluster-api-provider-bootbox
""")
    out = subprocess.run(["kubectl", "kustomize", tmp], check=True, capture_output=True, text=True).stdout
out = out.replace("namespace: NAMESPACE_PLACEHOLDER", "namespace: {{ .Release.Namespace }}")
# Keep CRDs on uninstall: deleting them would delete every host and machine.
out = out.replace("kind: CustomResourceDefinition\nmetadata:\n",
                  "kind: CustomResourceDefinition\nmetadata:\n  annotations:\n    helm.sh/resource-policy: keep\n")
(chart / "templates" / "generated.yaml").write_text(
    "# Generated by hack/gen-provider-chart.py from config/crd and config/rbac; do not edit.\n" + out)
